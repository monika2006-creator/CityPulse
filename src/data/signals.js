export const getActiveSignals = () => signals.filter((s) => s.status === "active");

export const getRecentSignals = (count = 5) =>
  [...signals].sort((a, b) => (a.detectedAt < b.detectedAt ? 1 : -1)).slice(0, count);

export const getCriticalSignals = () => signals.filter((s) => s.severity === "critical");

export const getSignalsByArea = (area) =>
  signals.filter((s) => s.area.toLowerCase() === area.toLowerCase());

export const getSignalsByType = (type) => signals.filter((s) => s.type === type);
